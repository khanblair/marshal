// Makes the phone app's first screen look like the rest of Marshal. The screen is a plain page with
// no build step, so it cannot import the design tokens; this copies them instead, from the files
// packages/tokens generates, and the Atkinson Hyperlegible fonts the app uses. Run it with
// `pnpm --filter mobile theme` after the tokens change. A test fails when the copy has drifted, so
// the two cannot disagree for long.
//
// Light colors are the default and the phone's own dark setting switches to the dark ones, the way
// docs/mobile.md section 5.5 asks. Nothing is read from the network, and the fonts are files in the
// app.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const tokens = join(root, "..", "..", "packages", "tokens");
const REGULAR = 400;
const MEDIUM = 500;
const SEMIBOLD = 600;
const BOLD = 700;
const WEIGHTS = [REGULAR, MEDIUM, SEMIBOLD, BOLD];
const FONT_FAMILY = "Atkinson Hyperlegible Next";
const FAMILY_STACK = `"${FONT_FAMILY}", ui-sans-serif, system-ui, sans-serif`;
/** The face the design sets addresses, ids and keys in. One weight is all the first screen uses. */
const MONO_FAMILY = "Atkinson Hyperlegible Mono";
const MONO_STACK = `"${MONO_FAMILY}", ui-monospace, "SF Mono", Menlo, Consolas, monospace`;
const MONO_FILE = "atkinson-hyperlegible-mono-latin-400-normal.woff2";

/** The `--color-*` lines of a block of generated CSS, as `name: value` pairs, in order. */
function colorsIn(css) {
  return [...css.matchAll(/^\s*(--color-[a-z0-9-]+):\s*([^;]+);/gm)].map(([, name, value]) => [
    name,
    value.trim(),
  ]);
}

/** The text between the braces of the first block that starts with `opener`. */
function blockOf(css, opener) {
  const start = css.indexOf(opener);
  if (start < 0) throw new Error(`packages/tokens has no ${opener} block. Run its gen script.`);
  const open = css.indexOf("{", start);
  return css.slice(open + 1, css.indexOf("\n}", open));
}

const declarations = (pairs, indent) =>
  pairs.map(([name, value]) => `${indent}${name}: ${value};`).join("\n");

/** The whole stylesheet, from the light tokens, the dark tokens, and the names of the font files. */
export function buildThemeCss(lightCss, darkCss) {
  const light = colorsIn(blockOf(lightCss, "@theme"));
  const dark = colorsIn(blockOf(darkCss, '[data-theme="dark"]'));
  if (light.length === 0 || dark.length === 0) throw new Error("The token files hold no colors.");
  const faces = WEIGHTS.map(
    (weight) => `@font-face {
  font-family: "${FONT_FAMILY}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("fonts/atkinson-hyperlegible-next-latin-${weight}-normal.woff2") format("woff2");
}`,
  ).join("\n");
  const mono = `@font-face {
  font-family: "${MONO_FAMILY}";
  font-style: normal;
  font-weight: ${REGULAR};
  font-display: swap;
  src: url("fonts/${MONO_FILE}") format("woff2");
}`;
  return `/* Generated by scripts/build-splash-theme.mjs from packages/tokens. Do not edit. */

${faces}
${mono}

:root {
  color-scheme: light dark;
  --font-sans: ${FAMILY_STACK};
  --font-mono: ${MONO_STACK};
${declarations(light, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root {
${declarations(dark, "    ")}
  }
}
`;
}

/** What `theme.css` should hold right now. */
export function currentThemeCss() {
  const light = readFileSync(join(tokens, "dist", "tailwind-theme.css"), "utf8");
  const dark = readFileSync(join(tokens, "dist", "tokens.css"), "utf8");
  return buildThemeCss(light, dark);
}

function main() {
  const splash = join(root, "splash");
  writeFileSync(join(splash, "theme.css"), currentThemeCss());
  const files = join(
    dirname(
      createRequire(join(tokens, "package.json")).resolve(
        "@fontsource/atkinson-hyperlegible-next/package.json",
      ),
    ),
    "files",
  );
  const monoFiles = join(
    dirname(
      createRequire(join(tokens, "package.json")).resolve(
        "@fontsource/atkinson-hyperlegible-mono/package.json",
      ),
    ),
    "files",
  );
  mkdirSync(join(splash, "fonts"), { recursive: true });
  for (const weight of WEIGHTS) {
    const name = `atkinson-hyperlegible-next-latin-${weight}-normal.woff2`;
    copyFileSync(join(files, name), join(splash, "fonts", name));
  }
  copyFileSync(join(monoFiles, MONO_FILE), join(splash, "fonts", MONO_FILE));
  process.stdout.write("The first screen's colors and fonts match packages/tokens.\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
